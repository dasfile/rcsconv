//! Compile the manifest and VERSIONINFO into `rcsconv-gui.exe`.
//!
//! Works only for the Windows GNU target: `windres` is taken from `PATH` (MinGW,
//! `C:\mingw64\bin\windres.exe` on the owner's machine). On other platforms
//! the step is skipped, so `cargo check` on Linux passes without resources.
//!
//! `VERSIONINFO` is not hard-coded: this script writes `version.h` with the version
//! taken from `CARGO_PKG_VERSION_*`, so the resources can never drift away from
//! `Cargo.toml`.

use std::env;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=res/app.rc");
    println!("cargo:rerun-if-changed=res/app.manifest");
    println!("cargo:rerun-if-env-changed=WINDRES");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if target_os != "windows" {
        return;
    }
    if env::var("CARGO_CFG_TARGET_ENV").as_deref() != Ok("gnu") {
        // MSVC is not used in this project (.clinerules 10), it needs no resources.
        println!("cargo:warning=resources are compiled for the Windows GNU target only");
        return;
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let object = out_dir.join("app_res.o");
    let windres = env::var("WINDRES").unwrap_or_else(|_| "windres".to_string());

    let major = env::var("CARGO_PKG_VERSION_MAJOR").unwrap_or_else(|_| "1".to_string());
    let minor = env::var("CARGO_PKG_VERSION_MINOR").unwrap_or_else(|_| "0".to_string());
    let patch = env::var("CARGO_PKG_VERSION_PATCH").unwrap_or_else(|_| "0".to_string());
    let version_h = format!(
        "/* generated by build.rs from Cargo.toml */\n\
         #define RC_VERSION_MAJOR {major}\n\
         #define RC_VERSION_MINOR {minor}\n\
         #define RC_VERSION_PATCH {patch}\n\
         #define RC_VERSION_STRING \"{major}.{minor}.{patch}.0\"\n"
    );
    std::fs::write(out_dir.join("version.h"), version_h)
        .expect("write version.h for windres");

    let status = Command::new(&windres)
        .args([
            "--input",
            "res/app.rc",
            "--output-format=coff",
            "--include-dir=res",
        ])
        .arg(format!("--include-dir={}", out_dir.display()))
        .arg(&object)
        .status();

    match status {
        Ok(status) if status.success() => {
            println!("cargo:rustc-link-arg={}", object.display());
        }
        Ok(status) => panic!("windres exited with code {status}: the manifest was not compiled"),
        Err(err) => println!(
            "cargo:warning=windres not found ({err}): the GUI will build without a manifest \
             (no comctl32 v6 visual styles, no DPI settings)"
        ),
    }
}
